import puppeteer from "puppeteer-core"
const wait = (ms) => new Promise(r => setTimeout(r, ms))
const b = await puppeteer.connect({ browserURL: "http://127.0.0.1:9333", defaultViewport: { width: 1600, height: 900 } })
const p = await b.newPage(); await p.bringToFront()
await p.goto("http://127.0.0.1:4180", { waitUntil: "networkidle2" }); await wait(4200)
await p.evaluate(() => { const old = console.error; console.error = (...a) => { (window.__errs = window.__errs || []).push(a.map(x => (x && x.stack) || String(x)).join(' | ')); old(...a) } })
await p.click(".title-menu .btn.primary"); await wait(1600)
await p.evaluate(() => [...document.querySelectorAll("button")].find(x => /以此机体开始/.test(x.textContent))?.click())
await wait(3000)
await p.evaluate(() => { const g = window.__rustfall; g.inventory.add("laser_pistol",1); g.inventory.add("ammo_laser",30); g.equipItem("laser_pistol") })
await wait(1200)
for (let i=0;i<3;i++){ await p.keyboard.down("KeyJ"); await wait(200); await p.keyboard.up("KeyJ"); await wait(200) }
await wait(1500)
const errs = await p.evaluate(() => (window.__errs || []).slice(0, 4))
console.log(JSON.stringify(errs, null, 1).slice(0, 3000))
await p.close(); await b.disconnect()
