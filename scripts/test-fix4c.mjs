import puppeteer from "puppeteer-core"
const wait=(ms)=>new Promise(r=>setTimeout(r,ms))
const b=await puppeteer.connect({browserURL:"http://127.0.0.1:9333",defaultViewport:{width:1600,height:900}})
const p=await b.newPage(); await p.bringToFront()
const errs=[]; p.on("pageerror",e=>errs.push(e.message.slice(0,180))); p.on("console",m=>{if(m.type()==="error")errs.push(m.text().slice(0,180))})
await p.goto("http://127.0.0.1:4180",{waitUntil:"networkidle2"})
await p.evaluate(()=>localStorage.removeItem("rustfall.settings.v1"))
await p.reload({waitUntil:"networkidle2"}); await wait(4700)
console.log("DEFAULTS", JSON.stringify(await p.evaluate(()=>({...window.__G.settings}))))
await p.evaluate(()=>document.querySelector(".title-menu .btn.primary")?.click()); await wait(1600)
await p.evaluate(()=>[...document.querySelectorAll("button")].find(x=>/以此机体开始/.test(x.textContent))?.click()); await wait(3000)
console.log("GLOW DEFAULT", JSON.stringify(await p.evaluate(()=>({glow:window.__G.settings.glow, visible:window.__rustfall.robot.glow?.visible, opacity:window.__rustfall.robot.glow?.material.opacity}))))
const clip=await p.evaluate(()=>{ const g=window.__rustfall; const v=g.viewSize()
  const sx=((g.robot.centerX-(g.camWorld.x-v.w/2))/v.w)*1600
  const sy=((g.camWorld.y-g.robot.centerY+v.h/2)/v.h)*900
  return {x:Math.max(0,Math.round(sx-130)),y:Math.max(0,Math.round(sy-130))} })
await wait(900); await p.screenshot({path:"screenshots-v3/fix-glow-off-closeup.png",clip:{x:clip.x,y:clip.y,width:260,height:260}})
// 暂停 → 设置（F2）层级
await p.keyboard.press("Escape"); await wait(600)
const pause=await p.evaluate(()=>({phase:window.__G.phase, pause:!!document.querySelector(".overlay.z-pause")}))
await p.keyboard.press("F2"); await wait(700)
const stack=await p.evaluate(()=>({panel:window.__G.ui.panel, pauseVisible:!!document.querySelector(".overlay.z-pause"), panelZ:getComputedStyle(document.querySelector(".overlay.z-panel")).zIndex}))
await p.keyboard.press("Escape"); await wait(500)
const back=await p.evaluate(()=>({phase:window.__G.phase, pauseVisible:!!document.querySelector(".overlay.z-pause"), panel:window.__G.ui.panel}))
console.log("PAUSE STACK", JSON.stringify({pause, stack, back}))
// 20x CPU 限速测时间比
const cdp=await p.createCDPSession(); await cdp.send("Emulation.setCPUThrottlingRate",{rate:20})
const t0=await p.evaluate(()=>({w:performance.now(),g:window.__rustfall.time,f:window.__G.fps}))
await wait(3000)
const t1=await p.evaluate(()=>({w:performance.now(),g:window.__rustfall.time,f:window.__G.fps}))
await cdp.send("Emulation.setCPUThrottlingRate",{rate:1})
console.log("THROTTLE20 ratio=", ((t1.g-t0.g)/((t1.w-t0.w)/1000)).toFixed(3), "fps0=",t0.f,"fps1=",t1.f)
console.log("ERR", JSON.stringify(errs.slice(0,5)))
await p.close(); await b.disconnect()
