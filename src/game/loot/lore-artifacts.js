/** 全部遗物（含数据类） */
export function allArtifacts() {
  return Content.filter(KIND.ITEM, (d) => d.category === 'artifact' || d.category === 'data')
}

/** 按 id 前缀取一组，例如 'diary_' */
export function artifactsByPrefix(prefix) {
  return allArtifacts().filter((d) => String(d.id).startsWith(prefix))
}

/** 遗物总数 */
export function artifactCount() {
  return allArtifacts().length
}
